"""Mixed fidelity (step 2.12, `02` §1.6): a run records the fidelity era of each trade date in
run.json, and its fidelity check reruns the period its ticks cover from flat at its own fidelity,
at 1-second, and at 1-minute fidelity (Done means 1)."""

import json
import os
import shutil
from datetime import date

import polars as pl
import pytest

import fefat as ff
import gen_fixtures
from fefat.backtest import (
    FidelityCheck,
    FidelityEra,
    PeriodOutcome,
    RefusedCheck,
    Run,
    RunConfig,
    fidelity_check,
)
from fefat.config import resolve_paths
from fefat.market.fidelity import TickFidelity
from fefat.market.schema import Timeframe
from notebook_runs import breakout, store_with

ES_TICK = 250_000_000
FIRST, TICKS_FROM, LAST = "2026-03-02", "2026-03-10", "2026-03-13"
ONE_SECOND, ONE_MINUTE = Timeframe.parse("1s"), Timeframe.parse("1m")


@pytest.fixture(name="ticks_for_the_last_sessions")
def fixture_ticks_for_the_last_sessions() -> None:
    """ESH2026's sessions from 2026-03-02 to 03-13 in `FEFAT_DATA_DIR`, with 1-minute bars
    throughout and trades and 1-second bars from 03-10, as a year with ticks for its last quarter
    holds them, generated by `scripts/gen_fixtures.py`."""
    synthetic = resolve_paths(os.environ).data_dir / "synthetic"
    dates = ["--dates", f"{FIRST}..{LAST}", "--contracts", "ESH2026", "--ticks-from", TICKS_FROM]
    assert gen_fixtures.main(["--out", str(synthetic), *dates]) == 0


@pytest.fixture(name="fixture_store")
def fixture_fixture_store() -> None:
    """The fixtures' ES and BTC trades, 1-second, and 1-minute bars, and BTC's funding."""
    store_with("trades", "ohlcv-1s", "ohlcv-1m", "funding")


@pytest.mark.usefixtures("ticks_for_the_last_sessions")
def test_a_run_records_its_fidelity_eras_and_checks_the_period_its_ticks_cover() -> None:
    # Done means 1. The roll calendar decides a session's front from the session before (D-44),
    # so the run starts on the data's second session, 03-03, at 1-minute fidelity.
    run = ff.backtest.run(breakout(), FIRST, LAST)

    bars = FidelityEra(
        first=date(2026, 3, 3), last=date(2026, 3, 9), trade_dates=5, fidelity=ONE_MINUTE
    )
    ticks = FidelityEra(
        first=date(2026, 3, 10), last=date(2026, 3, 13), trade_dates=4, fidelity=TickFidelity.TRADES
    )
    assert run.record.fidelity_eras == (bars, ticks)
    stored = json.loads((run.folder / "run.json").read_bytes())
    assert stored["fidelity_eras"] == [
        {"first": "2026-03-03", "last": "2026-03-09", "trade_dates": 5, "fidelity": "1m"},
        {"first": "2026-03-10", "last": "2026-03-13", "trade_dates": 4, "fidelity": "trades"},
    ]
    assert run.record.signal_source == ONE_MINUTE
    assert (run.record.window.start, run.record.window.end) == (date(2026, 3, 3), date(2026, 3, 13))
    check = run.metrics.fidelity_check
    assert isinstance(check, FidelityCheck)
    assert (check.first, check.last) == (date(2026, 3, 10), date(2026, 3, 13))
    assert check.baseline.fidelity == TickFidelity.TRADES
    assert check.baseline.eras == (ticks,)
    assert check.baseline.trades > 0
    for rerun, level in ((check.at_one_second, ONE_SECOND), (check.at_one_minute, ONE_MINUTE)):
        outcome = rerun.outcome
        assert outcome.eras == (ticks.model_copy(update={"fidelity": level}),)
        assert rerun.trades_delta == outcome.trades - check.baseline.trades
        assert rerun.pnl_delta == outcome.pnl - check.baseline.pnl
        assert rerun.max_drawdown_delta == outcome.max_drawdown - check.baseline.max_drawdown
        assert len(rerun.fill_prices) + rerun.unmatched_trades == check.baseline.trades
        assert len(rerun.fill_prices) + rerun.extra_trades == outcome.trades
    assert stored["metrics"]["fidelity_check"] == json.loads(check.model_dump_json())
    assert fidelity_check(run) == check


@pytest.mark.usefixtures("fixture_store")
def test_with_ticks_throughout_the_baseline_is_the_run_and_each_rerun_the_run_at_its_level() -> (
    None
):
    # The fixtures hold ticks on every date, so the period is the window: the baseline is the run
    # itself, and the reruns at 1 second and 1 minute are the runs capped there, under the run's
    # own settings (F-SLP-01).
    run = ff.backtest.run(breakout(), "2026-03-05", "2026-03-09")
    seconds = ff.backtest.run(
        breakout(), "2026-03-05", "2026-03-09", RunConfig(fidelity=ONE_SECOND)
    )
    minutes = ff.backtest.run(
        breakout(), "2026-03-05", "2026-03-09", RunConfig(fidelity=ONE_MINUTE)
    )

    check = run.metrics.fidelity_check

    assert isinstance(check, FidelityCheck)
    assert check.baseline == outcome_of(run)
    assert check.at_one_second.outcome == outcome_of(seconds)
    assert check.at_one_minute.outcome == outcome_of(minutes)
    keys = ["entry_decision", "side"]
    both = run.trades.join(minutes.trades, on=keys, suffix="_minute", maintain_order="left")
    entries = (pl.col("entry_price_minute") - pl.col("entry_price")) / ES_TICK
    exits = (pl.col("exit_price_minute") - pl.col("exit_price")) / ES_TICK
    differences = both.select(entries.alias("entry"), exits.alias("exit")).rows()
    found = [(price.entry_ticks, price.exit_ticks) for price in check.at_one_minute.fill_prices]
    assert found == differences
    assert check.at_one_minute.unmatched_trades == run.trades.height - both.height
    assert minutes.metrics.fidelity_check is None


@pytest.mark.usefixtures("fixture_store")
def test_a_rerun_the_engine_refuses_refuses_the_check_and_not_the_run() -> None:
    # BTC's trades without bars: no level at or coarser than 1 second to rerun its day at.
    synthetic = resolve_paths(os.environ).data_dir / "synthetic"
    for bars in ("ohlcv-1s", "ohlcv-1m"):
        shutil.rmtree(synthetic / bars / "root=BTCUSDT-PERP")

    run = ff.backtest.run(long_btc(), "2026-03-07", "2026-03-07")

    check = run.metrics.fidelity_check
    assert isinstance(check, RefusedCheck)
    assert (check.first, check.last, check.fidelity) == (
        date(2026, 3, 7),
        date(2026, 3, 7),
        ONE_SECOND,
    )
    assert check.refused.startswith("Expected a level at or coarser than 1s on 2026-03-07")
    day = date(2026, 3, 7)
    trades = FidelityEra(first=day, last=day, trade_dates=1, fidelity=TickFidelity.TRADES)
    assert run.record.fidelity_eras == (trades,)


def outcome_of(run: Run) -> PeriodOutcome:
    """A whole run as the check's outcome of a period."""
    return PeriodOutcome(
        fidelity=run.config.fidelity,
        eras=run.record.fidelity_eras,
        trades=run.trades.height,
        pnl=run.metrics.pnl,
        max_drawdown=run.metrics.drawdown.max_drawdown,
    )


def long_btc() -> ff.SignalStrategy:
    """A long of 0.1 BTC from 01:00 to 23:00 UTC, without a stop."""
    utc = pl.from_epoch("ts_close", time_unit="ns")
    at = lambda hour: (utc.dt.hour() == hour) & (utc.dt.minute() == 0)  # noqa: E731
    return ff.SignalStrategy(
        instrument="BTCUSDT-PERP",
        timeframe="5m",
        long_entry=at(1),
        short_entry=pl.lit(False),
        long_exit=at(23),
        execution=ff.Execution(entry=ff.Market(), sizing=ff.Fixed(0.1)),
    )
