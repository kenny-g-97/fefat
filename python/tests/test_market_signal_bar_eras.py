"""The level each trade date's signal bars are built from (D-71, step 3.2): the finest that holds
the date among the trades and bars that build the timeframe, so that a date's bars never depend
on the dates after it, as a choice over a whole window made them (the leakage audit of the
Phase 2 exit)."""

import os
import shutil
from datetime import date

import pytest

import gen_fixtures
from fefat.config import resolve_paths
from fefat.market.dataset_choice import provider_datasets, signal_bar_eras
from fefat.market.fidelity import ONE_MINUTE, FidelityEra, TickFidelity
from fefat.market.schema import Timeframe
from fefat.market.store import Store
from notebook_runs import store_with

FIVE_MINUTES = Timeframe.parse("5m")


@pytest.fixture(name="trades_inside_the_window")
def fixture_trades_inside_the_window() -> Store:
    """ESH2026's 1-minute bars from 2026-03-02 to 03-13 and its trades and 1-second bars of
    03-10 and 03-11 alone, generated by `scripts/gen_fixtures.py`: finer data that covers part
    of a window."""
    synthetic = resolve_paths(os.environ).data_dir / "synthetic"
    dates = ["--dates", "2026-03-02..2026-03-13", "--contracts", "ESH2026"]
    assert gen_fixtures.main(["--out", str(synthetic), *dates, "--ticks-from", "2026-03-10"]) == 0
    for schema in ("trades", "ohlcv-1s"):
        for day in ("2026-03-12", "2026-03-13"):
            shutil.rmtree(synthetic / schema / "root=ES" / "contract=ESH2026" / f"date={day}")
    return Store(synthetic.parent)


def era(first: date, last: date, trade_dates: int, level: TickFidelity | Timeframe) -> FidelityEra:
    return FidelityEra(first=first, last=last, trade_dates=trade_dates, fidelity=level)


@pytest.fixture(name="fixture_store")
def fixture_fixture_store() -> Store:
    """The fixtures' ES trades, 1-second, and 1-minute bars of 2026-03-05, 03-06, and 03-09."""
    store_with("trades", "ohlcv-1s", "ohlcv-1m")
    return Store(resolve_paths(os.environ).data_dir)


def test_a_date_without_finer_data_takes_the_next_finest_level(fixture_store: Store) -> None:
    # Step 2.12's code review, read per date: a level that holds fewer dates of a window no
    # longer cuts the window to it, and each date takes its finest level, trades, then 1-second,
    # then 1-minute bars, as `load` chooses, whose trades give the vwap an import's bars lack.
    held = provider_datasets(fixture_store, "ES", None, None)
    window = (date(2026, 3, 5), date(2026, 3, 9))
    synthetic = fixture_store.folder / "synthetic"
    trades = era(date(2026, 3, 5), date(2026, 3, 6), 2, TickFidelity.TRADES)
    monday = date(2026, 3, 9)
    assert signal_bar_eras(fixture_store, held, FIVE_MINUTES, window) == (
        era(date(2026, 3, 5), monday, 3, TickFidelity.TRADES),
    )

    for folder in (synthetic / "trades" / "root=ES").glob("contract=*/date=2026-03-09"):
        shutil.rmtree(folder)
    seconds = era(monday, monday, 1, Timeframe.parse("1s"))
    assert signal_bar_eras(fixture_store, held, FIVE_MINUTES, window) == (trades, seconds)

    for folder in (synthetic / "ohlcv-1s" / "root=ES").glob("contract=*/date=2026-03-09"):
        shutil.rmtree(folder)
    minutes = era(monday, monday, 1, ONE_MINUTE)
    assert signal_bar_eras(fixture_store, held, FIVE_MINUTES, window) == (trades, minutes)


def test_a_date_between_two_of_a_levels_dates_takes_its_own_finest_level(
    fixture_store: Store,
) -> None:
    # The Phase 2 exit's reviews: trades of 03-05 and 03-09 alone span the window as the
    # 1-second bars do, but 03-06 takes the 1-second bars, so the grid never fills it with empty
    # buckets.
    held = provider_datasets(fixture_store, "ES", None, None)
    trades = fixture_store.folder / "synthetic" / "trades" / "root=ES"
    for friday in trades.glob("contract=*/date=2026-03-06"):
        shutil.rmtree(friday)

    eras = signal_bar_eras(fixture_store, held, FIVE_MINUTES, (date(2026, 3, 5), date(2026, 3, 9)))

    assert [(each.first, each.fidelity) for each in eras] == [
        (date(2026, 3, 5), TickFidelity.TRADES),
        (date(2026, 3, 6), Timeframe.parse("1s")),
        (date(2026, 3, 9), TickFidelity.TRADES),
    ]


def test_each_trade_date_takes_the_finest_level_that_holds_it_in_eras_of_dates_in_a_row(
    trades_inside_the_window: Store,
) -> None:
    held = provider_datasets(trades_inside_the_window, "ES", None, None)

    eras = signal_bar_eras(
        trades_inside_the_window, held, FIVE_MINUTES, (date(2026, 3, 2), date(2026, 3, 13))
    )

    assert eras == (
        era(date(2026, 3, 2), date(2026, 3, 9), 6, ONE_MINUTE),
        era(date(2026, 3, 10), date(2026, 3, 11), 2, TickFidelity.TRADES),
        era(date(2026, 3, 12), date(2026, 3, 13), 2, ONE_MINUTE),
    )


def test_a_trade_dates_level_is_the_same_in_a_window_ending_on_it_and_one_running_past_it(
    trades_inside_the_window: Store,
) -> None:
    # The leakage audit of the Phase 2 exit: over 03-10 to 03-13 the 1-minute bars hold four
    # dates and the trades two, so a choice over the window built 03-10 from the bars, and over
    # 03-10 to 03-11, where both hold two, from the trades.
    held = provider_datasets(trades_inside_the_window, "ES", None, None)

    ending = signal_bar_eras(
        trades_inside_the_window, held, FIVE_MINUTES, (date(2026, 3, 10), date(2026, 3, 11))
    )
    running_past = signal_bar_eras(
        trades_inside_the_window, held, FIVE_MINUTES, (date(2026, 3, 10), date(2026, 3, 13))
    )

    trades = era(date(2026, 3, 10), date(2026, 3, 11), 2, TickFidelity.TRADES)
    assert ending == (trades,)
    assert running_past[0] == trades


@pytest.mark.parametrize(
    ("schemas", "timeframe", "refusal"),
    [
        ((), "5m", "Expected trades or bars to build signal bars from, got none"),
        (("ohlcv-1m",), "1s", "Expected a timeframe of 1m or coarser from 1-minute bars of ES"),
        (("ohlcv-1m",), "90s", "Expected trades, or bars whose length divides 90s, of ES"),
    ],
)
def test_data_that_builds_no_signal_bars_of_the_timeframe_is_refused(
    schemas: tuple[str, ...], timeframe: str, refusal: str
) -> None:
    store = Store(resolve_paths(os.environ).data_dir)
    for schema in schemas:
        shutil.copytree(
            gen_fixtures.ROOT / "fixtures" / "synthetic" / schema,
            store.folder / "synthetic" / schema,
        )
    held = provider_datasets(store, "ES", None, None) if schemas else {}

    with pytest.raises(ValueError, match=refusal):
        signal_bar_eras(
            store, held, Timeframe.parse(timeframe), (date(2026, 3, 5), date(2026, 3, 9))
        )
