"""The engine's benchmarks (step 2.15, `02-engine-and-data.md` §4 and §8 item 7, D-68).

Builds step 2.7's generated year of ES when it is missing (`notebooks/checks/2.07.ipynb`): its
trades, 1-second and 1-minute bars, generated by seed under `<FEFAT_HOME>/cache/`, never in the
repository, and its engine cache. Then runs `cargo bench` on it (`engine/crates/fefat-cli/benches/
engine.rs`), reads each benchmark's median from criterion's bencher lines, and compares it with a
stored baseline: a benchmark more than 30 % slower than its baseline gets a GitHub warning, and the
run still passes, since shared runners are too noisy for a gate and this PC's numbers in
`docs/validation/benchmarks.md` are the reference. It prints the next baseline as JSON, and in
GitHub Actions writes the table and that JSON to the job's summary.

    uv run python scripts/bench.py [--baseline docs/validation/benchmarks-ci-baseline.json]
"""

import argparse
import json
import os
import re
import subprocess
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import UTC, date, datetime
from pathlib import Path

import gen_fixtures
from fefat.config import FefatPaths, resolve_paths
from fefat.market import instruments
from fefat.market.calendar import build_sessions
from fefat.market.engine_cache import build_engine_cache
from fefat.market.engine_cache_index import ENGINE_CACHE_FOLDER_NAME
from fefat.market.store import Store

REPOSITORY = Path(__file__).resolve().parents[1]
ENGINE = REPOSITORY / "engine"
CI_BASELINE = "docs/validation/benchmarks-ci-baseline.json"
FIRST = date(2026, 1, 2)
LAST = date(2026, 12, 31)
CONTRACT = "ESH2026"
PLANTED_GAPS = "3"
REGRESSION_PERCENT = 30
"""A benchmark slower than its baseline by more than this warns (`02` §8 item 7)."""
BENCHER_LINE = re.compile(
    r"^test (?P<name>\S+) \.\.\. bench:\s+(?P<median>[\d,]+) ns/iter \(\+/- [\d,]+\)$"
)


@dataclass(frozen=True)
class Comparison:
    """A benchmark's median in this run beside its baseline's, in nanoseconds an iteration."""

    name: str
    median: int
    baseline: int | None

    @property
    def change(self) -> float | None:
        return None if self.baseline is None else self.median / self.baseline - 1

    @property
    def regressed(self) -> bool:
        if self.baseline is None:
            return False
        return self.median * 100 > self.baseline * (100 + REGRESSION_PERCENT)


def generated_year(paths: FefatPaths) -> Path:
    """The engine cache folder of ESH2026 in step 2.7's generated year, its sessions from `FIRST`
    through `LAST`: the year generated first when it is missing, and its cache built or brought up
    to date. A month the cache refuses refuses the benchmarks, which would time the others alone
    and read as a gain in speed."""
    calendar = instruments.get("ES").session_calendar()
    trade_dates = build_sessions(calendar, FIRST, LAST).get_column("trade_date")
    last = trade_dates[-1]
    year = paths.cache_dir / f"synthetic-es-{FIRST}-{last}"
    synthetic = year / "data" / "synthetic"
    if not (synthetic / "MANIFEST.json").is_file():
        print(f"Generating {trade_dates.len()} sessions of ES into {synthetic}", flush=True)
        dates = ["--dates", f"{FIRST}..{last}", "--contracts", CONTRACT]
        arguments = ["--out", str(synthetic), *dates, "--planted-gaps", PLANTED_GAPS]
        if gen_fixtures.main(arguments) != 0:
            raise RuntimeError(f"Expected gen_fixtures.py to write {synthetic}, it did not")
    build = build_engine_cache(Store(year / "data"), year / "cache", "ES", FIRST.year)
    if build.refused:
        raise RuntimeError(
            f"Expected every month of the year cached, got: {'; '.join(build.refused)}"
        )
    print(build.summary().splitlines()[0], flush=True)
    return year / "cache" / ENGINE_CACHE_FOLDER_NAME / build.provider / "ES" / CONTRACT


def run_benches(contract: Path) -> str:
    """Runs the benchmarks on the cache in `contract`, printing criterion's output as it comes,
    and returns that output."""
    command = ["cargo", "bench", "--package", "fefat-cli", "--bench", "engine"]
    environment = {**os.environ, "FEFAT_BENCH_CONTRACT": str(contract)}
    lines: list[str] = []
    with subprocess.Popen(
        [*command, "--", "--output-format", "bencher"],
        cwd=ENGINE,
        env=environment,
        stdout=subprocess.PIPE,
        text=True,
        encoding="utf-8",
    ) as process:
        if process.stdout is None:
            raise RuntimeError("Expected cargo bench's output to be piped, got none")
        for line in process.stdout:
            print(line, end="", flush=True)
            lines.append(line)
    if process.returncode != 0:
        raise RuntimeError(f"Expected cargo bench to pass, got exit code {process.returncode}")
    return "".join(lines)


def parse_medians(output: str) -> dict[str, int]:
    """Each benchmark's median in nanoseconds an iteration, from criterion's bencher lines."""
    lines = (BENCHER_LINE.match(line.strip()) for line in output.splitlines())
    medians = {line["name"]: int(line["median"].replace(",", "")) for line in lines if line}
    if not medians:
        raise ValueError(f"Expected cargo bench to report a benchmark, got:\n{output}")
    return medians


def stored_baseline(path: Path | None) -> dict[str, int]:
    """The medians of the baseline file at `path`, none without one."""
    if path is None:
        return {}
    stored = json.loads(path.read_text(encoding="utf-8"))
    medians = stored.get("ns_per_iter") if isinstance(stored, dict) else stored
    if not isinstance(medians, dict) or not all(
        isinstance(value, int) and value > 0 for value in medians.values()
    ):
        raise ValueError(
            f"Expected ns_per_iter to give positive nanoseconds by name in {path}, got {medians}"
        )
    return medians


def compare(medians: Mapping[str, int], baseline: Mapping[str, int]) -> list[Comparison]:
    """Each benchmark of this run beside its baseline, which may lack it; a baseline benchmark
    that did not run is refused, since its baseline file is stale."""
    missing = sorted(set(baseline) - set(medians))
    if missing:
        raise ValueError(
            f"Expected the benchmark {', '.join(missing)} in cargo bench's output, got "
            f"{', '.join(medians)}: rename or remove it in the baseline file"
        )
    return [Comparison(name, median, baseline.get(name)) for name, median in medians.items()]


def render_table(comparisons: Sequence[Comparison]) -> str:
    rows = [
        "| Benchmark | Median | Baseline | Change |",
        "| --- | ---: | ---: | ---: |",
    ]
    for comparison in comparisons:
        baseline = "none" if comparison.baseline is None else _milliseconds(comparison.baseline)
        change = "" if comparison.change is None else f"{comparison.change:+.1%}"
        rows.append(
            f"| {comparison.name} | {_milliseconds(comparison.median)} | {baseline} | {change} |"
        )
    return "\n".join(rows)


def regression_warnings(comparisons: Sequence[Comparison]) -> list[str]:
    """A GitHub warning for each benchmark over the regression threshold."""
    return [_warning(comparison) for comparison in comparisons if comparison.regressed]


def _warning(comparison: Comparison) -> str:
    message = (
        f"{comparison.name} {comparison.change:+.1%} against the runner baseline: "
        "compare on the reference PC (docs/validation/benchmarks.md)"
    )
    return "::warning title=Benchmark regression::" + message.replace("%", "%25")


def next_baseline(medians: Mapping[str, int], recorded: date, run: str | None) -> dict[str, object]:
    return {"recorded": recorded.isoformat(), "run": run, "ns_per_iter": dict(medians)}


def run_url(environment: Mapping[str, str]) -> str | None:
    """The GitHub Actions run this is, none outside one."""
    names = ("GITHUB_SERVER_URL", "GITHUB_REPOSITORY", "GITHUB_RUN_ID")
    if not all(name in environment for name in names):
        return None
    server, repository, run = (environment[name] for name in names)
    return f"{server}/{repository}/actions/runs/{run}"


def _milliseconds(nanoseconds: int) -> str:
    return f"{nanoseconds / 1_000_000:,.1f} ms"


def announce_failure(failure: Exception) -> None:
    """A GitHub warning that the benchmarks measured nothing, which the Benchmarks job's passing
    check would otherwise hide (`.github/workflows/benchmarks.yml`): the failure's first line."""
    message = f"The benchmarks measured nothing: {failure}".splitlines()[0]
    print(f"::warning title=Benchmarks did not run::{message.replace('%', '%25')}", flush=True)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the engine's benchmarks (step 2.15).")
    parser.add_argument("--baseline", type=Path, help=f"medians to compare with, as {CI_BASELINE}")
    arguments = parser.parse_args(argv)
    contract = generated_year(resolve_paths(os.environ))
    medians = parse_medians(run_benches(contract))
    comparisons = compare(medians, stored_baseline(arguments.baseline))
    table = render_table(comparisons)
    proposed = next_baseline(medians, datetime.now(UTC).date(), run_url(os.environ))
    baseline_json = json.dumps(proposed, indent=2)
    print(f"\n{table}\n")
    for warning in regression_warnings(comparisons):
        print(warning)
    print(f"This run as a baseline, for {CI_BASELINE} on a runner:\n{baseline_json}")
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary is not None:
        with Path(summary).open("a", encoding="utf-8") as file:
            file.write(f"## Benchmarks\n\n{table}\n\nThis run as a baseline, for `{CI_BASELINE}`:")
            file.write(f"\n\n```json\n{baseline_json}\n```\n")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as failure:
        announce_failure(failure)
        raise
